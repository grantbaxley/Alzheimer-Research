#!/usr/bin/env python3
"""Render awesome/README.md and evidence/README.md from the YAML sources.

python tools/build_docs.py          # write files
python tools/build_docs.py --check  # exit 1 if committed files are stale (used in CI)
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from alzres.registry import load, validate  # noqa: E402

LAYER_TITLES = {
    "progression": "Disease progression models and benchmarks",
    "imaging": "Neuroimaging pipelines and imaging ML",
    "simulation": "Brain simulators and whole-brain platforms",
    "spreading": "Mechanistic and spreading models",
    "atlases": "Atlases and connectome tools",
    "data": "Datasets and cohorts",
    "knowledge": "Targets, drugs, knowledge graphs and agents",
    "foundation_models": "Foundation models and biomarker models",
    "integrity_watchlist": "Integrity watchlist",
}
TRIAGE_TITLES = {
    "A": "Good starting points",
    "B": "Promising: vet and re-model first",
    "C": "Avoid / red flag",
}
GENERATED = "<!-- Generated by tools/build_docs.py from {src}. Do not edit by hand. -->\n\n"


def _cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def render_awesome(records) -> str:
    out = [GENERATED.format(src="registry/*.yaml")]
    out.append("# Open Alzheimer's research resources, graded\n\n")
    out.append(
        "A curated, skeptical list of open resources for modeling the brain and Alzheimer's "
        "disease. Grades come from the "
        "[2026-10 landscape review](../docs/landscape-2026-10/report.md) "
        "and are **not** endorsements: `our status` says what this project has actually "
        "checked. See [policy/VETTING.md](../policy/VETTING.md) for what each grade means.\n\n"
    )
    by_layer = defaultdict(list)
    for r in records:
        by_layer[r.path.stem].append(r)
    for layer in sorted(
        by_layer, key=lambda k: list(LAYER_TITLES).index(k) if k in LAYER_TITLES else 99
    ):
        out.append(f"## {LAYER_TITLES.get(layer, layer)}\n\n")
        for triage in ("A", "B", "C"):
            rows = [r for r in by_layer[layer] if r["triage"] == triage]
            if not rows:
                continue
            out.append(f"### {triage}: {TRIAGE_TITLES[triage]}\n\n")
            out.append("| Resource | License | Our status | Why |\n|---|---|---|---|\n")
            for r in sorted(rows, key=lambda r: r["name"].lower()):
                lic = r["license"]
                lic_txt = f"{lic['spdx']} ({lic['source']})"
                out.append(
                    f"| [{_cell(r['name'])}]({r['url']}) | {_cell(lic_txt)} | "
                    f"{r.get('our_status', 'not-started')} | {_cell(r['reason'])} |\n"
                )
            out.append("\n")
    return "".join(out)


def render_evidence(claims) -> str:
    out = [GENERATED.format(src="evidence/claims.yaml")]
    out.append("# Evidence grades: prevention, slowing and reversal\n\n")
    out.append(
        "Grades: **A** replicated/adequately powered RCTs on a clinical endpoint; **A-null** "
        "adequately powered RCT(s) with no benefit; **B** single RCT, subgroup, biomarker-only or "
        "strong natural experiment; **C** small, open-label, observational or mechanistic; **D** "
        "uncontrolled, animal-only or regulator-rejected; **pending** decisive trial not yet "
        "read out.\n\n"
        "No intervention has been shown to reverse Alzheimer's disease. Figures were taken from "
        "the landscape review and are not yet re-derived by this project (`verified` column).\n\n"
        "This is a research summary, not medical advice.\n\n"
    )
    out.append("| Claim | Grade | Evidence | Implication | Verified | Source |\n")
    out.append("|---|---|---|---|---|---|\n")
    for c in claims:
        src = " ".join(f"[{i + 1}]({u})" for i, u in enumerate(c.get("sources", [])))
        out.append(
            f"| {_cell(c['claim'])} | {c['grade']} | {_cell(c['effect'])} | "
            f"{_cell(c['implication'])} | {'yes' if c.get('verified_by_us') else 'no'} | {src} |\n"
        )
    return "".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    records = load(ROOT / "registry")
    problems = validate(records)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    claims = yaml.safe_load((ROOT / "evidence" / "claims.yaml").read_text())["claims"]
    targets = {
        ROOT / "awesome" / "README.md": render_awesome(records),
        ROOT / "evidence" / "README.md": render_evidence(claims),
    }
    stale = []
    for path, text in targets.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(text)
    if stale:
        print(f"stale generated files: {stale}; run python tools/build_docs.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
